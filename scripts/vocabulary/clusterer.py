"""
Vocabulary clustering — group canonical keywords into themes and write
a draft YAML file for human review.
Workflow:
1. `build_vocabulary(keywords, llm)` — sends canonical keyword list to the LLM
   in chunks and asks it to propose theme groupings → writes config/concepts_draft.yaml.
2. `map_keywords_to_themes(keywords, concepts)` — for each keyword string,
   returns the list of theme names it belongs to (fuzzy match against
   concepts.yaml theme keyword lists, threshold=0.75).
3. `flag_unmapped(keywords, concepts, threshold)` — returns keywords that
   don't match any theme above the threshold so they can be reviewed.
The user reviews concepts_draft.yaml, edits it, and saves as concepts.yaml
before the brain build (Phase 9).
"""
from __future__ import annotations

import json
import logging
from pathlib import Path

import yaml

from scripts.llm.llm_client import LLMClient, parse_llm_json
from scripts.llm.prompt_registry import load_clustering_prompts
from scripts.llm.prompt_safety import sanitize_for_prompt

logger = logging.getLogger(__name__)

# Public so the CLI can reference the same path without hardcoding it twice.
CONCEPTS_DRAFT_PATH = Path("config/concepts_draft.yaml")

# Generated by clusters_to_topics_yaml() — human reviews and copies entries to
# topics.yaml.  Gitignored; never committed directly.
TOPICS_SUGGESTED_PATH = Path("config/topics_suggested.yaml")

# Fallback / hard-cap chunk size.  Smart sizing (N1, 2026-05-17) computes the
# actual chunk count from the LLM's num_ctx; this constant is used only as a
# safety floor / explicit hard cap when the user passes --chunk-size.
_CHUNK_SIZE = 60

# ── N1 smart-chunking constants (mirror extractor.py A6 math) ───────────────
_CHARS_PER_TOKEN: int = 4              # rule of thumb: English scientific text
_SAFETY_FACTOR: float = 0.75           # fraction of ctx to budget for input + output
_SYSTEM_PROMPT_RESERVE_TOKENS: int = 500   # system prompt overhead estimate
_FALLBACK_CTX: int = 8192              # build_vocabulary's traditional num_ctx
_MIN_KEYWORDS_PER_CHUNK: int = 20      # floor: never split below this; smaller chunks waste calls
_MAX_KEYWORDS_PER_CHUNK: int = 1000    # ceiling: even unlimited-context models cap here for sanity
_OUTPUT_MULTIPLIER: float = 1.5        # output JSON is roughly 1.5× input keyword text
_THEME_OVERHEAD_CHARS: int = 800       # ~10 themes × 80 chars each in JSON output

