def build_vocabulary(
    keywords: dict[str, list[str]],
    llm: LLMClient,
    output_path: Path = CONCEPTS_DRAFT_PATH,
    max_tokens: int = 16384,
    chunk_size: int = 0,
    remediate: bool = True,
    refine: bool = False,
    refine_llm: LLMClient | None = None,
    chunk_chars_override: int | None = None,
) -> dict:
    """
    Use the LLM to cluster canonical keywords into themes.

    Keywords are smart-chunked (N1, 2026-05-17): the chunk size is computed from
    the LLM's ``num_ctx`` so each prompt fills the available input budget without
    overrunning it.  All three passes (initial clustering, remediation, refinement)
    use the same sizing.  Pass ``chunk_size`` to enforce a HARD CAP (CLI
    ``--chunk-size``) — the smart sizing computes the natural maximum and
    ``chunk_size`` clamps it down further.

    After initial chunked clustering, two optional refinement passes are
    available:

    - *remediate* (default on): sends any unclustered keywords back to the LLM
      with the full list of identified theme names, asking it to assign each
      keyword to the closest existing theme.  Reduces leftover noise.

    - *refine* (default off): sends the complete merged clustering to the LLM
      in one call and asks it to identify cross-theme keyword assignments that
      were missed during per-chunk processing.  Useful when a keyword clearly
      belongs in two themes that were processed in different chunks.

    Parameters
    ----------
    keywords:
        Output of normalizer.normalise_keywords — {canonical: [variants]}.
    llm:
        Any LLMClient instance (OllamaClient in prod, MockLLMClient in tests).
        Used for chunked clustering and the remediation pass.
    output_path:
        Where to write concepts_draft.yaml. Defaults to config/concepts_draft.yaml.
    max_tokens:
        Max tokens per LLM response for the chunked clustering and remediation
        passes.  The refinement pass always uses max_tokens=32768 (positive cap,
        cloud-Ollama-safe) regardless of this value — see *refine_llm*.
    chunk_size:
        Hard cap on keywords per LLM call (CLI ``--chunk-size``).  ``0`` (default)
        or negative means "no cap — use smart sizing from num_ctx alone".  When
        provided, the effective chunk size is ``min(smart_size, chunk_size)``.
    remediate:
        If True (default), run _remediate_unclustered() after initial clustering.
    refine:
        If True (default False), run _refine_clustering() after remediation.
        Adds one extra LLM call over the full vocabulary — useful but slower.
    refine_llm:
        Optional separate LLMClient for the refinement pass.  The refinement
        prompt includes the full merged vocabulary; pass an OllamaClient with
        ``num_ctx=None`` here so the model uses its native context window for
        generation.  If None, the main *llm* is used.
    chunk_chars_override:
        Optional per-mode override from ``extraction.yaml build_vocabulary.chunk_chars``.
        Bypasses the num_ctx-derived budget when set.  Default None.

    Returns
    -------
    dict
        Parsed structure: {"themes": [...], "unclustered": [...]}.
        Also written to output_path as YAML.
    """
    canonical_list = sorted(keywords.keys())

    if not canonical_list:
        logger.warning("build_vocabulary: keyword list is empty — returning empty clusters")
        result: dict = {"themes": [], "unclustered": []}
        output_path.parent.mkdir(parents=True, exist_ok=True)
        with open(output_path, "w", encoding="utf-8") as f:
            yaml.dump(result, f, default_flow_style=False, allow_unicode=True, sort_keys=False)
        return result

    # N1: smart-size the chunks; the CLI `--chunk-size` (if >0) is a hard cap.
    user_cap = chunk_size if chunk_size and chunk_size > 0 else None
    effective_chunk_size = _keywords_per_chunk(
        llm, canonical_list,
        user_cap=user_cap,
        chunk_chars_override=chunk_chars_override,
    )
    chunks = _chunk_list(canonical_list, effective_chunk_size)
    n_chunks = len(chunks)
    merged: dict = {"themes": [], "unclustered": []}
    _prompts = load_clustering_prompts()

    for i, chunk in enumerate(chunks, start=1):
        logger.info(
            "build_vocabulary: clustering chunk %d/%d (%d keywords)…",
            i, n_chunks, len(chunk),
        )
        # C1: Zotero keyword strings are user-controllable; a malicious tag
        # could carry ChatML/Llama role markers into the clustering prompt.
        # Keywords are short → default fence-stripping is correct here.
        safe_chunk = [sanitize_for_prompt(kw) for kw in chunk]
        raw = llm.complete(_prompts.system, _prompts.render_user(safe_chunk), max_tokens=max_tokens)
        try:
            partial = parse_llm_json(raw)
        except ValueError as parse_exc:
            # Response was likely truncated at the token limit.  Attempt to salvage
            # whatever complete theme objects were serialised before the cutoff.
            logger.warning(
                "build_vocabulary: chunk %d/%d JSON parse failed (%s) — "
                "attempting partial recovery…",
                i, n_chunks, parse_exc,
            )
            partial = _recover_partial_json(raw)
            if partial is None:
                logger.error(
                    "build_vocabulary: chunk %d/%d — no themes recoverable; "
                    "skipping chunk. If this recurs, reduce --chunk-size (try 30).",
                    i, n_chunks,
                )
                continue
        if "themes" not in partial:
            partial["themes"] = []
        if "unclustered" not in partial:
            partial["unclustered"] = []
        _merge_clusters(merged, partial)
        logger.info(
            "build_vocabulary: chunk %d/%d done — %d themes so far",
            i, n_chunks, len(merged["themes"]),
        )

    # Optional post-processing passes
    if remediate:
        _remediate_unclustered(
            merged, llm, max_tokens, chunk_size,
            chunk_chars_override=chunk_chars_override,
        )
    if refine:
        # Use a separate LLM (no num_ctx cap) if the caller provided one.
        # The refinement prompt is the full vocabulary — too large for the
        # num_ctx=8192 ceiling used during chunked clustering.
        _effective_refine_llm = refine_llm if refine_llm is not None else llm
        _refine_debug_path = output_path.with_name(
            output_path.stem + "_refinement_raw.txt"
        )
        _refine_clustering(
            merged,
            _effective_refine_llm,
            # max_tokens=32768: positive cap, cloud-Ollama-safe (num_predict=-1
            # returns 400 on cloud Ollama); sized well above the ~7k refinement prompt.
            debug_output_path=_refine_debug_path,
        )

    # Write draft YAML
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        yaml.dump(merged, f, default_flow_style=False, allow_unicode=True, sort_keys=False)
    logger.info(
        "build_vocabulary: wrote %s — %d themes, %d unclustered keywords",
        output_path, len(merged["themes"]), len(merged["unclustered"]),
    )
    return merged


def _pick_query_terms(theme_name: str, keywords: list[str], max_terms: int = 4) -> list[str]:
    """
    Pick a small set of representative search terms from a theme's keyword list.

    Preference order:
    1. 2–3 word phrases — specific enough to be meaningful in a database search.
    2. If fewer than 2 preferred candidates exist, fall back to the full list
       sorted by length (longer → more specific).
    3. If the keyword list is empty, return the theme name lowercased as a
       last-resort term.

    The selected terms are passed to clusters_to_topics_yaml() to construct an
    OR-joined query string.  They are intentionally chosen for recall over
    precision because the user is expected to review and tighten queries before
    production use.
    """
    preferred = [kw for kw in keywords if 2 <= len(kw.split()) <= 3]
    if preferred:
        # Sort by total length ascending — shorter phrases are more likely to
        # appear verbatim in paper metadata.
        return sorted(preferred, key=len)[:max_terms]
    if keywords:
        # Fallback: sort by length descending (longer = more specific).
        return sorted(keywords, key=len, reverse=True)[:max_terms]
    return [theme_name.lower()]


def clusters_to_topics_yaml(
    clusters: dict,
    databases: list[str] | None = None,
) -> str:
    """
    Render clustered themes as a ``topics.yaml``-compatible search entry list.

    Each theme in *clusters* becomes one search entry.  The query is constructed
    by selecting a small number of representative keywords from the theme via
    ``_pick_query_terms()`` and joining them with OR.  Multi-word terms are
    double-quoted for exact-phrase matching in PubMed/arXiv.

    The output is a YAML string with a header comment indicating it is
    auto-generated.  Write it to ``TOPICS_SUGGESTED_PATH`` and diff it against
    the live ``topics.yaml`` before deciding which entries to incorporate.

    Parameters
    ----------
    clusters:
        Parsed clustering result — ``{"themes": [...], "unclustered": [...]}``.
        Typically the return value of ``build_vocabulary()``.
    databases:
        List of database identifiers for every generated search entry.
        Defaults to ``["pubmed", "arxiv"]`` — the two databases supported
        without an API key in findpapers 0.6.x.

    Returns
    -------
    str
        YAML text ready to write to a file.
    """
    if databases is None:
        databases = ["pubmed", "arxiv"]

    searches: list[dict] = []
    for theme in clusters.get("themes", []):
        name = theme.get("name", "Unknown Theme")
        kws = theme.get("keywords", [])
        terms = _pick_query_terms(name, kws)
        # Quote multi-word phrases for exact-phrase matching; leave single
        # words unquoted so the database can apply its own stemming.
        quoted = [f'"{t}"' if " " in t else t for t in terms]
        query = " OR ".join(quoted)
        searches.append({
            "name": name,
            "query": query,
            "databases": list(databases),
        })

    data: dict = {"searches": searches}
    header = (
        "# Auto-generated by lit-monitor build-vocabulary — review before using.\n"
        "# Each entry corresponds to one vocabulary theme. Edit queries before production use.\n"
        "# Databases: pubmed and arxiv need no API key; scopus requires SCOPUS_API_KEY.\n"
    )
    return header + yaml.dump(
        data, default_flow_style=False, allow_unicode=True, sort_keys=False
    )


def map_keywords_to_themes(
    keywords: list[str],
    concepts: dict,
    threshold: float = 0.75,
) -> dict[str, list[str]]:
    """
    For each keyword, return the theme names it belongs to.
    Matching is exact string equality (lower-cased) against the keyword
    lists in each theme, with a rapidfuzz fallback for near-matches above
    the threshold.
    Parameters
    ----------
    keywords:
        List of keyword strings to map.
    concepts:
        Parsed concepts.yaml content — {"themes": [...], "unclustered": [...]}.
    threshold:
        Similarity threshold (0.0–1.0) for fuzzy fallback matching.
    Returns
    -------
    dict[str, list[str]]
        {keyword: [theme_name, ...]} — empty list means unmapped.
    """
    from rapidfuzz import fuzz
    threshold_score = threshold * 100  # rapidfuzz uses 0–100 scale
    themes = concepts.get("themes", [])

    # Build lookup: theme_name → set of lower-cased keywords
    theme_index: dict[str, list[str]] = {}
    for theme in themes:
        name = theme.get("name", "")
        kws = [k.lower().strip() for k in theme.get("keywords", [])]
        theme_index[name] = kws
    result: dict[str, list[str]] = {}
    for kw in keywords:
        kw_lower = kw.lower().strip()
        matched_themes: list[str] = []
        for theme_name, theme_kws in theme_index.items():
            # Exact match first
            if kw_lower in theme_kws:
                matched_themes.append(theme_name)
                continue
            # Fuzzy fallback
            for theme_kw in theme_kws:
                score = fuzz.ratio(kw_lower, theme_kw)
                if score >= threshold_score:
                    matched_themes.append(theme_name)
                    break
        result[kw] = matched_themes
    return result


def flag_unmapped(
    keywords: list[str],
    concepts: dict,
    threshold: float = 0.75,
) -> list[str]:
    """
    Return keywords that don't match any theme above the threshold.
    These are candidates for adding to existing themes or creating new ones.
    They are NOT silently dropped — callers should log or surface these
    for human review.
    Parameters
    ----------
    keywords:
        List of keyword strings to check.
    concepts:
        Parsed concepts.yaml content.
    threshold:
        Similarity threshold. Same value used in map_keywords_to_themes.
    Returns
    -------
    list[str]
        Keywords with no matching theme.
    """
    mapping = map_keywords_to_themes(keywords, concepts, threshold=threshold)
    unmapped = [kw for kw, themes in mapping.items() if not themes]
    if unmapped:
        logger.warning(
            "%d unmapped keywords (no theme match above threshold=%.2f): %s",
            len(unmapped), threshold, unmapped,
        )
    return unmapped
