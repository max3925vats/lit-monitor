def _chunk_list(items: list, size: int) -> list[list]:
    """Split a list into successive sublists of at most `size` items."""
    return [items[i : i + size] for i in range(0, len(items), size)]


def _keywords_per_chunk(
    llm: LLMClient,
    keywords: list[str],
    *,
    user_cap: int | None = None,
    chunk_chars_override: int | None = None,
) -> int:
    """Compute keywords-per-chunk from the LLM's num_ctx (N1 smart chunking).

    Mirrors A6's `_available_input_chars` budget math but solves for keyword count
    instead of returning a character budget.  The clustering prompt has roughly:

        input  ≈ K × (avg_len + 5)              [keywords with separator overhead]
        output ≈ K × avg_len × _OUTPUT_MULTIPLIER + _THEME_OVERHEAD_CHARS

    Budget: (num_ctx × _SAFETY_FACTOR − system_overhead) × _CHARS_PER_TOKEN
            ≥ input + output

    Solving for K and clamping by [_MIN_KEYWORDS_PER_CHUNK, _MAX_KEYWORDS_PER_CHUNK]
    plus any `user_cap` (the CLI `--chunk-size` hard cap).

    Parameters
    ----------
    llm:
        LLMClient instance with a `num_ctx` attribute (OllamaClient sets this
        from /api/show, num_ctx_override, or a fallback).
    keywords:
        The list of keywords being chunked; used to compute the average length.
    user_cap:
        Optional CLI override from `--chunk-size`.  When provided, the returned
        chunk size is at most this value.  Use 0 or None to skip the cap.
    chunk_chars_override:
        Optional per-mode override from `extraction.yaml build_vocabulary.chunk_chars`.
        When provided, used as the input-character budget directly; overrides
        the num_ctx-derived computation.

    Returns
    -------
    int
        Keyword count per chunk, clamped to safe bounds.
    """
    if not keywords:
        return _MIN_KEYWORDS_PER_CHUNK
    avg_len = sum(len(k) for k in keywords) / len(keywords)
    if chunk_chars_override is not None and chunk_chars_override > 0:
        budget_chars: float = float(chunk_chars_override)
    else:
        ctx = getattr(llm, "num_ctx", None) or _FALLBACK_CTX
        budget_chars = (
            (ctx * _SAFETY_FACTOR - _SYSTEM_PROMPT_RESERVE_TOKENS)
            * _CHARS_PER_TOKEN
        )
    # Each keyword costs (input chars + output chars) per chunk.
    per_keyword_cost = (avg_len + 5) + (avg_len * _OUTPUT_MULTIPLIER)
    if per_keyword_cost <= 0:
        # Defensive: average length of 0 is impossible after the empty-list check
        # above, but keep the math safe.
        raw_k = _MAX_KEYWORDS_PER_CHUNK
    else:
        raw_k = int((budget_chars - _THEME_OVERHEAD_CHARS) / per_keyword_cost)
    k = max(_MIN_KEYWORDS_PER_CHUNK, min(raw_k, _MAX_KEYWORDS_PER_CHUNK))
    if user_cap is not None and user_cap > 0:
        k = min(k, user_cap)
    logger.info(
        "_keywords_per_chunk: ctx=%s avg_kw_len=%.1f → %d keywords/chunk (user_cap=%s, override=%s)",
        getattr(llm, "num_ctx", None), avg_len, k, user_cap, chunk_chars_override,
    )
    return k


def _merge_clusters(base: dict, partial: dict) -> None:
    """Merge a partial LLM cluster result into *base* in-place.

    Themes with the same name have their keyword lists unioned (order preserved,
    duplicates dropped). Unknown themes are appended. Unclustered lists are unioned.
    """
    # Build index: theme name → position in base["themes"]
    base_index: dict[str, int] = {t["name"]: i for i, t in enumerate(base["themes"])}

    for theme in partial.get("themes", []):
        name = theme.get("name", "").strip()
        if not name:
            continue
        new_kws: list[str] = theme.get("keywords", [])
        if name in base_index:
            existing = base["themes"][base_index[name]]["keywords"]
            seen = set(existing)
            for kw in new_kws:
                if kw not in seen:
                    existing.append(kw)
                    seen.add(kw)
        else:
            base["themes"].append({"name": name, "keywords": list(new_kws)})
            base_index[name] = len(base["themes"]) - 1

    # Union unclustered lists
    existing_unc = set(base.get("unclustered", []))
    for kw in partial.get("unclustered", []):
        if kw not in existing_unc:
            base["unclustered"].append(kw)
            existing_unc.add(kw)


def _recover_partial_json(raw: str) -> dict | None:
    """
    Salvage complete theme objects from a response that was truncated mid-JSON.

    When the output token limit is hit, any theme objects that were fully serialised
    before the truncation point are still valid.  This function scans the partial
    JSON string incrementally, collecting complete ``{"name": ..., "keywords": [...]}``
    objects, and returns them as a minimal valid result dict.

    Returns None if no complete theme objects can be extracted (total parse failure).
    """
    themes: list[dict] = []
    decoder = json.JSONDecoder()

    # Locate the start of the themes array — everything before it is structure we skip.
    themes_marker = raw.find('"themes"')
    if themes_marker == -1:
        return None
    array_start = raw.find('[', themes_marker)
    if array_start == -1:
        return None

    pos = array_start + 1
    while pos < len(raw):
        # Advance past whitespace and comma separators between objects.
        while pos < len(raw) and raw[pos] in ' \t\n\r,':
            pos += 1
        if pos >= len(raw) or raw[pos] != '{':
            break  # Either end of array or start of truncated object — stop.
        try:
            obj, end_pos = decoder.raw_decode(raw, pos)
        except json.JSONDecodeError:
            break  # Truncation point — abandon remainder.
        if isinstance(obj, dict) and "name" in obj and "keywords" in obj:
            themes.append(obj)
        pos = end_pos

    if not themes:
        return None

    logger.warning(
        "build_vocabulary: partial recovery — salvaged %d complete theme(s) from truncated response",
        len(themes),
    )
    return {"themes": themes, "unclustered": []}


def _recover_partial_refinement_json(raw: str) -> dict | None:
    """
    Salvage complete theme-additions entries from a truncated refinement response.

    When the output token limit is hit mid-JSON, any ``"ThemeName": [...]`` pairs
    that were fully serialised before the cutoff are still valid.  This function
    scans the partial ``"additions": {...}`` dict incrementally and collects every
    complete key-value pair it can find before hitting truncation.

    Returns None if no complete entries can be extracted.
    """
    additions: dict[str, list[str]] = {}
    decoder = json.JSONDecoder()

    # Locate the opening brace of the additions object.
    additions_marker = raw.find('"additions"')
    if additions_marker == -1:
        return None
    obj_start = raw.find('{', additions_marker)
    if obj_start == -1:
        return None

    pos = obj_start + 1
    while pos < len(raw):
        # Skip whitespace and the comma that separates successive entries.
        while pos < len(raw) and raw[pos] in ' \t\n\r,':
            pos += 1
        if pos >= len(raw) or raw[pos] != '"':
            break  # Closing brace, end of string, or truncation before the key.
        # Decode the theme name (a JSON string).
        try:
            theme_name, name_end = decoder.raw_decode(raw, pos)
        except json.JSONDecodeError:
            break
        if not isinstance(theme_name, str):
            break
        # Advance past the colon separating key from value.
        colon_pos = raw.find(':', name_end)
        if colon_pos == -1:
            break
        val_pos = colon_pos + 1
        while val_pos < len(raw) and raw[val_pos] in ' \t\n\r':
            val_pos += 1
        if val_pos >= len(raw) or raw[val_pos] != '[':
            break  # Value is missing or truncated before the opening bracket.
        # Decode the keyword array.
        try:
            keywords, arr_end = decoder.raw_decode(raw, val_pos)
        except json.JSONDecodeError:
            break  # Array is truncated — stop here, don't salvage partial arrays.
        if isinstance(keywords, list):
            additions[theme_name] = [k for k in keywords if isinstance(k, str)]
        pos = arr_end

    if not additions:
        return None

    logger.warning(
        "build_vocabulary: refinement partial recovery — salvaged %d theme addition(s)",
        len(additions),
    )
    return {"additions": additions}


def _remediate_unclustered(
    merged: dict,
    llm: LLMClient,
    max_tokens: int,
    chunk_size: int,
    *,
    chunk_chars_override: int | None = None,
) -> None:
    """
    Assign unclustered keywords into existing themes where possible.

    Sends the unclustered list + current theme names to the LLM and asks it
    to place each keyword into one or more existing themes (or confirm it stays
    unclustered).  Modifies *merged* in place.  Unclustered keywords that the
    LLM cannot place are preserved in merged["unclustered"].

    Parameters
    ----------
    merged:
        The accumulated cluster result to update in place.
    llm:
        LLMClient instance to use for the remediation call(s).
    max_tokens:
        Max output tokens per LLM call.
    chunk_size:
        Hard-cap on keywords per remediation chunk (CLI ``--chunk-size``).
        ``0`` or negative disables the cap; smart sizing (N1) computes the
        actual count from ``llm.num_ctx``.
    chunk_chars_override:
        Optional per-mode override from ``extraction.yaml``; bypasses the
        num_ctx-derived budget for the smart-sizing computation.
    """
    unclustered = merged.get("unclustered", [])
    if not unclustered:
        logger.info("build_vocabulary: no unclustered keywords — skipping remediation pass")
        return

    theme_names = [t["name"] for t in merged.get("themes", [])]
    if not theme_names:
        logger.warning(
            "build_vocabulary: no themes exist — cannot remediate %d unclustered keywords",
            len(unclustered),
        )
        return

    logger.info(
        "build_vocabulary: remediating %d unclustered keywords against %d themes…",
        len(unclustered), len(theme_names),
    )

    # N1: smart-size the chunks; honor the CLI hard-cap when set.
    user_cap = chunk_size if chunk_size and chunk_size > 0 else None
    effective_chunk_size = _keywords_per_chunk(
        llm, unclustered,
        user_cap=user_cap,
        chunk_chars_override=chunk_chars_override,
    )
    chunks = _chunk_list(unclustered, effective_chunk_size)
    still_unclustered: list[str] = []
    # Rebuild index each time we enter this function so it reflects the
    # current merged["themes"] state.
    theme_index: dict[str, int] = {t["name"]: i for i, t in enumerate(merged["themes"])}
    _prompts = load_clustering_prompts()

    for i, chunk in enumerate(chunks, start=1):
        if len(chunks) > 1:
            logger.info(
                "build_vocabulary: remediation chunk %d/%d (%d keywords)…",
                i, len(chunks), len(chunk),
            )
        # C1 review: theme names and unclustered keywords are echoed back from
        # the merged vocabulary, which is built from user-controllable Zotero
        # keyword strings. Scrub role markers before rendering — these never
        # reached the main-loop's safe_chunk sanitization. Short strings →
        # default fence-stripping.
        safe_theme_names = [sanitize_for_prompt(name) for name in theme_names]
        safe_chunk = [sanitize_for_prompt(kw) for kw in chunk]
        raw = llm.complete(
            _prompts.remediation_system,
            _prompts.render_remediation_user(safe_theme_names, safe_chunk),
            max_tokens=max_tokens,
        )
        try:
            result = parse_llm_json(raw)
        except ValueError as exc:
            logger.warning(
                "build_vocabulary: remediation chunk %d/%d failed to parse (%s) — "
                "leaving %d keywords unclustered",
                i, len(chunks), exc, len(chunk),
            )
            still_unclustered.extend(chunk)
            continue

        for kw, assigned_themes in result.get("assignments", {}).items():
            for theme_name in assigned_themes:
                if theme_name not in theme_index:
                    logger.debug(
                        "build_vocabulary: remediation — unknown theme %r for kw %r, skipped",
                        theme_name, kw,
                    )
                    continue
                existing = merged["themes"][theme_index[theme_name]]["keywords"]
                if kw not in existing:
                    existing.append(kw)

        still_unclustered.extend(result.get("still_unclustered", []))

    n_placed = len(unclustered) - len(still_unclustered)
    logger.info(
        "build_vocabulary: remediation complete — %d placed, %d still unclustered",
        n_placed, len(still_unclustered),
    )
    merged["unclustered"] = still_unclustered


def _refine_clustering(
    merged: dict,
    llm: LLMClient,
    max_tokens: int = 32768,
    debug_output_path: Path | None = None,
) -> None:
    """
    Global cross-theme refinement pass.

    Sends the full merged clustering to the LLM and asks it to identify keywords
    that should appear in additional themes beyond their current placement.
    Only additions are applied — existing assignments are never removed.
    Modifies *merged* in place.

    Parameters
    ----------
    merged:
        The accumulated cluster result to update in place.
    llm:
        LLMClient instance to use for the refinement call.
    max_tokens:
        Max output tokens for the refinement LLM call.  Defaults to 32768 —
        a cloud-Ollama-safe positive cap that still accommodates the additions
        JSON for large vocabularies (150+ themes), which can easily exceed
        16 000 tokens.  Pass an explicit smaller value only when the calling
        context has a hard ceiling and you want a graceful truncation +
        partial-recovery path.
    debug_output_path:
        If provided, the raw LLM response is written to this path unconditionally
        (before any parsing attempt) so the caller can inspect truncation or
        unexpected content even when the pass succeeds.  Useful for diagnosing
        output size issues on large libraries.
    """
    if not merged.get("themes"):
        logger.info("build_vocabulary: no themes — skipping refinement pass")
        return

    logger.info("build_vocabulary: running global cross-theme refinement pass…")
    _prompts = load_clustering_prompts()
    # C1 review: the refinement prompt renders every theme name and keyword
    # string from the merged vocabulary (all user-controllable Zotero keywords)
    # raw. Sanitize the rendered prompt so a role marker in any keyword cannot
    # break out. Short strings → default fence-stripping.
    refinement_user = sanitize_for_prompt(_prompts.render_refinement_user(merged))

    # N1 smart-sizing awareness for refinement: estimate prompt cost and WARN
    # if it exceeds the model's safe input budget.  Refinement is by design a
    # single full-vocabulary call, so we cannot chunk-split here — we warn
    # loudly so the user knows to either (a) raise num_ctx_override, (b) shrink
    # the vocabulary, or (c) accept truncation.
    refinement_input_chars = len(refinement_user) + len(_prompts.refinement_system)
    ctx = getattr(llm, "num_ctx", None)
    if ctx:
        budget_chars = int((ctx * _SAFETY_FACTOR - _SYSTEM_PROMPT_RESERVE_TOKENS) * _CHARS_PER_TOKEN)
        if refinement_input_chars > budget_chars:
            logger.warning(
                "build_vocabulary: refinement prompt (%d chars) exceeds smart budget "
                "(%d chars at num_ctx=%d).  Output may truncate.  Consider raising "
                "num_ctx_override or shrinking the vocabulary.",
                refinement_input_chars, budget_chars, ctx,
            )
        else:
            logger.info(
                "build_vocabulary: refinement prompt %d chars / budget %d (num_ctx=%d) — OK",
                refinement_input_chars, budget_chars, ctx,
            )
    # ctx=None (e.g. refine_llm built with num_ctx=None) means "use full native context";
    # no budget check possible — proceed.

    raw = llm.complete(
        _prompts.refinement_system,
        refinement_user,
        max_tokens=max_tokens,
    )

    # Persist the raw response unconditionally so the caller can verify the
    # pass completed and diagnose truncation even when parsing succeeds.
    if debug_output_path is not None:
        try:
            debug_output_path.parent.mkdir(parents=True, exist_ok=True)
            debug_output_path.write_text(raw, encoding="utf-8")
            logger.info(
                "build_vocabulary: refinement raw response (%d chars) saved to %s",
                len(raw), debug_output_path,
            )
        except OSError as exc:
            logger.warning(
                "build_vocabulary: could not write refinement debug output: %s", exc
            )

    try:
        result = parse_llm_json(raw)
    except ValueError as exc:
        # Response may have been truncated.  Attempt to salvage whatever complete
        # "ThemeName": [...] entries were serialised before the cutoff.
        logger.warning(
            "build_vocabulary: refinement pass failed to parse (%s) — "
            "attempting partial recovery…",
            exc,
        )
        result = _recover_partial_refinement_json(raw)
        if result is None:
            logger.warning(
                "build_vocabulary: refinement partial recovery found nothing — "
                "skipping refinement pass"
            )
            return

    theme_index: dict[str, int] = {t["name"]: i for i, t in enumerate(merged["themes"])}
    n_added = 0
    for theme_name, new_kws in result.get("additions", {}).items():
        if theme_name not in theme_index:
            logger.debug(
                "build_vocabulary: refinement — unknown theme %r, skipped", theme_name
            )
            continue
        existing = merged["themes"][theme_index[theme_name]]["keywords"]
        existing_set = set(existing)
        for kw in new_kws:
            if kw not in existing_set:
                existing.append(kw)
                existing_set.add(kw)
                n_added += 1

    logger.info(
        "build_vocabulary: refinement complete — %d cross-theme keywords added", n_added
    )


